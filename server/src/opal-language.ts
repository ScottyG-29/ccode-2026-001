/**
 * OPAL language definitions — verbs, functions, data types, and their documentation.
 * This serves as the single source of truth for IntelliSense, hover info, and diagnostics.
 */

export interface OpalItem {
  name: string;
  kind: "verb" | "function" | "type" | "keyword" | "operator";
  category: string;
  signature?: string;
  description: string;
  documentation?: string;
  parameters?: OpalParameter[];
  returnType?: string;
  accelerable?: boolean;
}

export interface OpalParameter {
  name: string;
  type: string;
  description: string;
  optional?: boolean;
  defaultValue?: string;
}

