// ---------------------------------------------------------------------------
// Convenience: all items combined
// ---------------------------------------------------------------------------

export const ALL_OPAL_ITEMS: OpalItem[] = [
  ...OPAL_VERBS,
  ...OPAL_FUNCTIONS,
  ...OPAL_DATA_TYPES,
  ...OPAL_KEYWORDS,
];

/**
 * Lookup an OPAL item by name (case-insensitive).
 */
export function findOpalItem(name: string): OpalItem | undefined {
  const lower = name.toLowerCase();
  return ALL_OPAL_ITEMS.find((item) => item.name.toLowerCase() === lower);
}

/**
 * Get all OPAL verb names.
 */
export function getVerbNames(): string[] {
  return OPAL_VERBS.map((v) => v.name);
}

/**
 * Get all OPAL function names.
 */
export function getFunctionNames(): string[] {
  return OPAL_FUNCTIONS.map((f) => f.name);
}
